-- Run this once in the Supabase SQL editor.
-- Full workout data is owner-only. Friends can query workout and exercise-name overviews only.
-- The global leaderboard exposes display names and aggregate totals, never raw sets.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 1 and 80),
  friend_code text not null unique check (friend_code ~ '^[A-Z0-9]{6,12}$'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Personal measurements are separated from discoverable profiles so friends
-- and leaderboard users can never read them through the profiles API.
create table if not exists public.profile_details (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  first_name text not null check (char_length(btrim(first_name)) between 1 and 60),
  last_name text not null check (char_length(btrim(last_name)) between 1 and 60),
  age smallint not null check (age between 13 and 120),
  gender text not null check (gender in ('male', 'female', 'non_binary', 'other', 'prefer_not_to_say')),
  weight_kg numeric(6,2) not null check (weight_kg between 20 and 500),
  height_cm numeric(5,2) not null check (height_cm between 80 and 300),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.user_states (
  user_id uuid primary key references auth.users(id) on delete cascade,
  state jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.friendships (
  id bigint generated by default as identity primary key,
  requester_id uuid not null references public.profiles(id) on delete cascade,
  addressee_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (requester_id <> addressee_id)
);

create unique index if not exists friendships_unique_pair
  on public.friendships (least(requester_id, addressee_id), greatest(requester_id, addressee_id));
create index if not exists friendships_requester_status on public.friendships (requester_id, status);
create index if not exists friendships_addressee_status on public.friendships (addressee_id, status);
create index if not exists profiles_display_name_lower_pattern
  on public.profiles (lower(display_name) text_pattern_ops);

create table if not exists public.workout_overviews (
  id text primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  workout_name text not null check (char_length(workout_name) between 1 and 80),
  started_at timestamptz not null,
  duration_ms bigint not null default 0 check (duration_ms >= 0),
  exercise_count integer not null default 0 check (exercise_count >= 0),
  total_sets integer not null default 0 check (total_sets >= 0),
  total_volume numeric not null default 0 check (total_volume >= 0),
  workout_date date not null,
  units text not null default 'kg' check (units in ('kg','lbs')),
  exercise_names text[] not null default '{}'::text[],
  created_at timestamptz not null default now()
);
alter table public.workout_overviews add column if not exists total_volume numeric not null default 0 check (total_volume >= 0);
alter table public.workout_overviews add column if not exists workout_date date;
alter table public.workout_overviews add column if not exists exercise_names text[] not null default '{}'::text[];
update public.workout_overviews set workout_date=(started_at at time zone 'UTC')::date where workout_date is null;
alter table public.workout_overviews alter column workout_date set not null;
create index if not exists workout_overviews_user_started on public.workout_overviews (user_id, started_at desc);

