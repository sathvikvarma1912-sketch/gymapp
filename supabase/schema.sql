create or replace function public.friend_leaderboard(range_start timestamptz default null)
returns table (
  user_id uuid,
  workout_days bigint,
  workout_count bigint,
  total_sets bigint,
  total_volume_kg numeric
)
language sql
stable
security invoker
set search_path = ''
as $$
  select
    o.user_id,
    count(distinct o.workout_date) as workout_days,
    count(*) as workout_count,
    sum(o.total_sets)::bigint as total_sets,
    round(sum(case when o.units = 'lbs' then o.total_volume * 0.45359237 else o.total_volume end), 2) as total_volume_kg
  from public.workout_overviews o
  where range_start is null or o.started_at >= range_start
  group by o.user_id;
$$;
revoke all on function public.friend_leaderboard(timestamptz) from public;
revoke all on function public.friend_leaderboard(timestamptz) from anon;
grant execute on function public.friend_leaderboard(timestamptz) to authenticated;

drop function if exists public.global_leaderboard(timestamptz);
create or replace function public.global_leaderboard(leader_period text default 'all')
returns table (
  user_id uuid,
  display_name text,
  workout_days bigint,
  workout_count bigint,
  total_sets bigint,
  total_volume_kg numeric
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  period_start timestamptz;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  if leader_period not in ('week', 'month', 'year', 'all') then
    raise exception 'Unsupported leaderboard period' using errcode = '22023';
  end if;

  period_start := case leader_period
    when 'week' then date_trunc('day', now()) - extract(dow from now()) * interval '1 day'
    when 'month' then date_trunc('month', now())
    when 'year' then date_trunc('year', now())
    else null
  end;

  return query
  select
    p.id,
    p.display_name,
    count(distinct o.workout_date) as workout_days,
    count(o.id) as workout_count,
    coalesce(sum(o.total_sets), 0)::bigint as total_sets,
    round(
      coalesce(
        sum(
          case
            when o.units = 'lbs' then o.total_volume * 0.45359237
            else o.total_volume
          end
        ),
        0
      ),
      2
    ) as total_volume_kg
  from public.profiles p
  left join public.workout_overviews o
    on o.user_id = p.id
   and (period_start is null or o.started_at >= period_start)
  group by p.id, p.display_name;
end;
$$;
revoke all on function public.global_leaderboard(text) from public;
revoke all on function public.global_leaderboard(text) from anon;
grant execute on function public.global_leaderboard(text) to authenticated;

create or replace function public.find_profile_by_friend_code(search_code text)
returns table (id uuid, display_name text)
language sql
stable
security definer set search_path = ''
as $$
  select p.id, p.display_name
  from public.profiles p
  where (select auth.uid()) is not null
    and p.friend_code = upper(trim(search_code))
  limit 1;
$$;
revoke all on function public.find_profile_by_friend_code(text) from public;
revoke all on function public.find_profile_by_friend_code(text) from anon;
grant execute on function public.find_profile_by_friend_code(text) to authenticated;

create or replace function public.search_profiles_by_name(search_term text)
returns table (id uuid, display_name text)
language sql
stable
security definer
set search_path = ''
as $$
  select p.id, p.display_name
  from public.profiles p
  where (select auth.uid()) is not null
    and p.id <> (select auth.uid())
    and char_length(btrim(search_term)) between 2 and 80
    and btrim(search_term) !~ '[%_]'
    and lower(p.display_name) like lower(btrim(search_term)) || '%'
  order by
    case when lower(p.display_name) = lower(btrim(search_term)) then 0 else 1 end,
    lower(p.display_name),
    p.id
  limit 10;
$$;
revoke all on function public.search_profiles_by_name(text) from public;
revoke all on function public.search_profiles_by_name(text) from anon;
grant execute on function public.search_profiles_by_name(text) to authenticated;

create or replace function public.make_profile_for_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name, friend_code)
  values (
    new.id,
    left(coalesce(nullif(new.raw_user_meta_data ->> 'display_name',''), split_part(new.email,'@',1), 'Lifter'), 80),
    upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8))
  );
  return new;
end;
$$;
revoke all on function public.make_profile_for_new_user() from public;
revoke all on function public.make_profile_for_new_user() from anon;
revoke all on function public.make_profile_for_new_user() from authenticated;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.make_profile_for_new_user();
